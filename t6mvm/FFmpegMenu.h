	static std::string GetCFG()
	{
		const char* extraArgs = T6SDK::Dvars::GetString(CustomDvars::dvar_ffmpeg_extraArgs);
		return std::string("//FFMPEG //GENERATED BY T6MVM. REQUIRES T6MVM TO BE LOADED.\n") +
			"mvm_ffmpeg_codec " + std::to_string(T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_codec)) + ";\n" +
			"mvm_ffmpeg_quality " + std::to_string(T6SDK::Dvars::GetFloat(CustomDvars::dvar_ffmpeg_quality)) + ";\n" +
			"mvm_ffmpeg_preset " + std::to_string(T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_preset)) + ";\n" +
			"mvm_ffmpeg_pixelFormat " + std::to_string(T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_pixelFormat)) + ";\n" +
			"mvm_ffmpeg_container " + std::to_string(T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_container)) + ";\n" +
			"mvm_ffmpeg_faststart " + std::to_string(T6SDK::Dvars::GetBool(CustomDvars::dvar_ffmpeg_faststart) ? 1 : 0) + ";\n" +
			"mvm_ffmpeg_extraArgs \"" + (extraArgs ? extraArgs : "") + "\";\n";
	}

	static void OnExtraArgsButton()
	{
		UIControls::UI_FFmpegExtraArgsDialog.Show([](std::string value)
		{
			T6SDK::Dvars::SetString(CustomDvars::dvar_ffmpeg_extraArgs, value.c_str());
			CustomDvars::dvar_ffmpeg_extraArgs->modified = true;
		});
	}

	static void ResetToDefaults()
	{
		T6SDK::Dvars::SetInt(CustomDvars::dvar_ffmpeg_codec, 0);
		T6SDK::Dvars::SetFloat(CustomDvars::dvar_ffmpeg_quality, 18.0f);
		T6SDK::Dvars::SetInt(CustomDvars::dvar_ffmpeg_preset, 1);
		T6SDK::Dvars::SetInt(CustomDvars::dvar_ffmpeg_pixelFormat, 0);
		T6SDK::Dvars::SetInt(CustomDvars::dvar_ffmpeg_container, 0);
		T6SDK::Dvars::SetBool(CustomDvars::dvar_ffmpeg_faststart, true);
		T6SDK::Dvars::SetString(CustomDvars::dvar_ffmpeg_extraArgs, "");
		T6SDK::ConsoleLog::LogTagged(T6SDK::ConsoleLog::C_INFO, false, "FFMPEG", "FFmpeg settings reset to H.264/MP4 defaults.");
	}

	static void Draw()
	{
		if (!*UIControls::FFmpegTabButton.isChecked)
			return;

		vec2_t titleCoords = T6SDK::Drawing::GetGridCellCoords(8, 4);
		T6SDK::Drawing::DrawTextAbsolute("^9FFMPEG ENCODING SETTINGS", titleCoords.x, titleCoords.y, 1.0f, T6SDK::Drawing::T_WHITECOLOR, T6SDK::AnchorPoint::Center, 0x00);

		const int codec = T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_codec);
		const int preset = T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_preset);
		const int pixelFormat = T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_pixelFormat);
		const int container = T6SDK::Dvars::GetInt(CustomDvars::dvar_ffmpeg_container);

		UIControls::UI_FFmpegCodecEnum.Text = CodecLabels[FFmpeg::Clamp(codec, 0, 5)];
		UIControls::UI_FFmpegCodecEnum.Draw();

		UIControls::UI_FFmpegQuality.Draw();

		UIControls::UI_FFmpegPresetEnum.Text = PresetLabels[FFmpeg::Clamp(preset, 0, 4)];
		UIControls::UI_FFmpegPresetEnum.Draw();

		UIControls::UI_FFmpegPixelFormatEnum.Text = PixelFormatLabels[FFmpeg::Clamp(pixelFormat, 0, 4)];
		UIControls::UI_FFmpegPixelFormatEnum.Draw();

		UIControls::UI_FFmpegContainerEnum.Text = ContainerLabels[FFmpeg::Clamp(container, 0, 4)];
		UIControls::UI_FFmpegContainerEnum.Draw();

		UIControls::UI_FFmpegFaststartCheckBox.Draw();

		static std::string extraArgsText;
		const char* extraArgs = T6SDK::Dvars::GetString(CustomDvars::dvar_ffmpeg_extraArgs);
		extraArgsText = (extraArgs && extraArgs[0]) ? (std::string("EXTRA ARGS: ") + extraArgs) : std::string("EXTRA ARGS: none (click to set)");
		UIControls::UI_FFmpegExtraArgsButton.Text = extraArgsText.c_str();
		UIControls::UI_FFmpegExtraArgsButton.Draw();

		UIControls::UI_FFmpegResetButton.Draw();

		vec2_t note1 = T6SDK::Drawing::GetGridCellCoords(4, 24);
		T6SDK::Drawing::DrawTextAbsolute("^7Quality (CRF) is used by H.264/H.265/AV1/VP9.", note1.x, note1.y, 1.0f, T6SDK::Drawing::T_WHITECOLOR, T6SDK::AnchorPoint::TopLeft, 0x00);
		vec2_t note2 = T6SDK::Drawing::GetGridCellCoords(4, 26);
		T6SDK::Drawing::DrawTextAbsolute("^7ProRes and UtVideo are lossless; quality and preset are ignored.", note2.x, note2.y, 1.0f, T6SDK::Drawing::T_WHITECOLOR, T6SDK::AnchorPoint::TopLeft, 0x00);
	}

